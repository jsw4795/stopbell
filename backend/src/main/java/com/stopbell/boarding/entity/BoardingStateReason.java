package com.stopbell.boarding.entity;

public enum BoardingStateReason {
    TEMPORARY_PROVIDER_FAILURE, STALE_PROGRESS, VEHICLE_MISSING, IDENTITY_CONFLICT,
    PROGRESS_REGRESSION, TRAVERSAL_AMBIGUOUS, CONTINUITY_GAP_EXCEEDED, METADATA_CHANGED,
    ARRIVAL_OBSERVED, PASSED_OBSERVED, USER_CANCELLED, SESSION_LIFETIME_EXPIRED;

    public boolean isSuspension() {
        return switch (this) {
            case TEMPORARY_PROVIDER_FAILURE, STALE_PROGRESS, VEHICLE_MISSING, IDENTITY_CONFLICT,
                    PROGRESS_REGRESSION, TRAVERSAL_AMBIGUOUS, CONTINUITY_GAP_EXCEEDED, METADATA_CHANGED -> true;
            default -> false;
        };
    }
}
